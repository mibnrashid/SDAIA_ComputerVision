"""precompute_clip.py — real CLIP scores for the Zero-Shot Showdown activity.

Run once in Colab (CPU is fine), from the repo root:

    !git clone https://github.com/mibnrashid/SDAIA_ComputerVision
    %cd SDAIA_ComputerVision
    !pip install -q cairosvg
    !python tools/precompute_clip.py

It reads the ten SVG scenes and their captions from
activities/data/showdown-scenes.js, renders each SVG to a 224 x 224 PNG
with cairosvg, scores the four captions with openai/clip-vit-base-patch32
(softmax over the four), and writes:

    activities/data/showdown.json   (the data, for reference)
    activities/data/showdown.js     (window.SHOWDOWN = {...}; read by the page)

Commit both files. Until this script has been run, the page shows
"Teacher setup needed".
"""
import datetime
import io
import json
import os

import torch
import torch.nn.functional as F
from PIL import Image
from transformers import CLIPModel, CLIPProcessor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'activities', 'data')
MODEL = 'openai/clip-vit-base-patch32'


def load_scenes():
    text = open(os.path.join(DATA, 'showdown-scenes.js'), encoding='utf-8').read()
    start, end = text.index('['), text.rindex(']')
    return json.loads(text[start:end + 1])


def render(svg):
    """SVG -> 224x224 RGB. cairosvg if it loads (Colab/Linux); otherwise
    headless Chrome (Windows, where the cairo DLL is usually missing)."""
    try:
        import cairosvg
        png = cairosvg.svg2png(bytestring=svg.encode('utf-8'), output_width=224, output_height=224)
        return Image.open(io.BytesIO(png)).convert('RGB')
    except (ImportError, OSError):
        return render_chrome(svg)


def render_chrome(svg):
    import subprocess
    import sys
    import tempfile
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from browser_check import chrome, file_url
    tmp = tempfile.mkdtemp(prefix='cvd-svg-')
    page, out = os.path.join(tmp, 's.html'), os.path.join(tmp, 's.png')
    with open(page, 'w', encoding='utf-8') as fh:
        fh.write('<!doctype html><meta charset="utf-8"><style>html,body{margin:0;background:#fff}'
                 'svg{display:block;width:448px;height:448px}</style>' + svg)
    subprocess.run([chrome(), '--headless=new', '--disable-gpu', '--hide-scrollbars', f'--user-data-dir={tmp}',
                    '--window-size=448,448', f'--screenshot={out}', file_url(page)], capture_output=True, timeout=120)
    return Image.open(out).convert('RGB').crop((0, 0, 448, 448)).resize((224, 224), Image.LANCZOS)


def as_tensor(out):
    return out if torch.is_tensor(out) else out.pooler_output


@torch.no_grad()
def main():
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    model = CLIPModel.from_pretrained(MODEL).to(device).eval()
    proc = CLIPProcessor.from_pretrained(MODEL)
    scale = model.logit_scale.exp().item()
    results = []
    for s in load_scenes():
        img = render(s['svg'])
        img.save(os.path.join(DATA, f"showdown-{s['id']}.png"))
        ii = proc(images=img, return_tensors='pt').to(device)
        ti = proc(text=s['captions'], return_tensors='pt', padding=True).to(device)
        ie = F.normalize(as_tensor(model.get_image_features(**ii)), dim=-1)
        te = F.normalize(as_tensor(model.get_text_features(**ti)), dim=-1)
        sims = (ie @ te.T).squeeze(0)
        probs = (scale * sims).softmax(-1)
        best = int(probs.argmax())
        results.append({'id': s['id'], 'cosine': [round(float(v), 4) for v in sims],
                        'probs': [round(float(v), 4) for v in probs], 'best': best})
        print(f"{s['id']:<8} best = {s['captions'][best]!r}  " + '  '.join(f'{p:.2f}' for p in probs.tolist()))
    data = {'model': MODEL, 'generated': datetime.datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC'),
            'note': 'softmax over the four captions of each scene, CLIP logit scale applied', 'scenes': results}
    with open(os.path.join(DATA, 'showdown.json'), 'w', encoding='utf-8') as fh:
        json.dump(data, fh, indent=1)
    with open(os.path.join(DATA, 'showdown.js'), 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/precompute_clip.py — real CLIP scores. */\nwindow.SHOWDOWN = ' + json.dumps(data) + ';\n')
    print('wrote activities/data/showdown.json and showdown.js — commit both, then reload the activity page.')


if __name__ == '__main__':
    main()
