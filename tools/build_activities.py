"""build_activities.py — write every activity page in activities/.

    python tools/build_activities.py

All data is bundled inline (no fetch, no model in the browser), so every
page works from disk. Zero-Shot Showdown reads its CLIP scores from
activities/data/showdown.js, written by tools/precompute_clip.py; until
then a placeholder (window.SHOWDOWN = null) makes the page show
"Teacher setup needed".
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from act.chrome import act_page  # noqa: E402
from act import day1, day2, day3  # noqa: E402
from _page import page  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def registry():
    js = open(os.path.join(ROOT, 'assets', 'activities.js'), encoding='utf-8').read()
    out = {}
    for m in re.finditer(r"id: '([^']+)', num: '(\d+)', day: (\d), minutes: (\d+), max: (\d+).*?file: '([^']+)', title: '([^']+)'", js, re.S):
        out[m.group(1)] = dict(id=m.group(1), num=m.group(2), day=int(m.group(3)), minutes=int(m.group(4)),
                               max=int(m.group(5)), file=m.group(6), title=m.group(7))
    return out


def write(path, text):
    with open(os.path.join(ROOT, path), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote', path)


def main():
    reg = registry()
    builders = {
        'pixel-detective': day1.pixel_detective, 'be-the-kernel': day1.be_the_kernel,
        'shape-race': day1.shape_race, 'spot-the-bug': day1.spot_the_bug,
        'iou-darts': day2.iou_darts, 'be-nms': day2.be_nms, 'threshold-tycoon': day2.threshold_tycoon,
        'zero-shot-showdown': day3.zero_shot_showdown, 'fool-the-model': day3.fool_the_model,
    }
    os.makedirs(os.path.join(ROOT, 'activities', 'data'), exist_ok=True)
    scenes = [{'id': s['id'], 'svg': s['svg'], 'captions': s['captions']} for s in day3.SCENES]
    write('activities/data/showdown-scenes.js',
          '/* Generated by tools/build_activities.py. tools/precompute_clip.py reads the same scenes. */\n'
          'window.SHOWDOWN_SCENES = ' + json.dumps(scenes, indent=1) + ';\n')
    placeholder = os.path.join(ROOT, 'activities', 'data', 'showdown.js')
    if not os.path.exists(placeholder):
        write('activities/data/showdown.js',
              '/* Placeholder. Run tools/precompute_clip.py in Colab to replace this file with real CLIP scores. */\n'
              'window.SHOWDOWN = null;\n')
    for aid, fn in builders.items():
        meta = reg[aid]
        style, body, script, how = fn()
        extra = ''
        if aid == 'zero-shot-showdown':
            extra = '  <script src="./data/showdown-scenes.js"></script>\n  <script src="./data/showdown.js"></script>'
        rounds = 'Image' if aid == 'pixel-detective' else ('Business' if aid == 'threshold-tycoon' else 'Round')
        write('activities/' + meta['file'], act_page(meta, how, body, script, style, rounds, extra))
    write('activities/print-signs.html', signs())


