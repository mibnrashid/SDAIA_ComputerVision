"""build_assessments.py — pre-test, post-test and theory exam.

    python tools/build_assessments.py

Reads tools/assess/items.py (correct option written first), places each
correct option at the letter given by the fixed key, then checks:
  * item counts 20 / 20 / 30
  * key distribution: pre 5/5/5/5, post 5/5/5/5, exam 8/8/7/7
  * day coverage: pre/post 7/7/6, exam 15/15 (Days 1–2 only)
  * option lengths within ±20 % of the item's mean (options under 8
    characters on average — numbers and short formulas — are exempt)
  * the correct option is the strictly longest in at most 30 % of items
Writes content/assessments.md, assessment/questions.js (no answers) and
assessment/keys.js (answer keys + explanations, base64-encoded).
"""
import base64
import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from assess.items import KEYS, PRETEST, POSTTEST, EXAM  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = 'ABCD'
SETS = {'pretest': PRETEST, 'posttest': POSTTEST, 'exam': EXAM}
WANT_KEYS = {'pretest': {'A': 5, 'B': 5, 'C': 5, 'D': 5}, 'posttest': {'A': 5, 'B': 5, 'C': 5, 'D': 5},
             'exam': {'A': 8, 'B': 8, 'C': 7, 'D': 7}}
WANT_DAYS = {'pretest': {1: 7, 2: 7, 3: 6}, 'posttest': {1: 7, 2: 7, 3: 6}, 'exam': {1: 15, 2: 15}}
WANT_N = {'pretest': 20, 'posttest': 20, 'exam': 30}
TITLES = {'pretest': 'Pre-test', 'posttest': 'Post-test', 'exam': 'Theory exam'}


def arrange(items, key):
    out = []
    for it, k in zip(items, key):
        pos = L.index(k)
        opts = list(it['o'][1:])
        opts.insert(pos, it['o'][0])
        out.append(dict(it, options=opts, answer=pos, letter=k))
    return out


def length_issues(item):
    lens = [len(o) for o in item['o']]
    mean = sum(lens) / 4
    if mean < 8:
        return None
    bad = [o for o in item['o'] if abs(len(o) - mean) > 0.2 * mean]
    return bad or None


def longest_correct(item):
    lens = [len(o) for o in item['o']]
    return lens[0] > max(lens[1:])


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    problems, built, report = [], {}, []
    for name, items in SETS.items():
        key = KEYS[name]
        if len(items) != WANT_N[name] or len(key) != WANT_N[name]:
            problems.append(f'{name}: {len(items)} items / key length {len(key)}, want {WANT_N[name]}')
        kc = Counter(key)
        if dict(kc) != WANT_KEYS[name]:
            problems.append(f'{name}: key distribution {dict(sorted(kc.items()))}, want {WANT_KEYS[name]}')
        dc = Counter(it['day'] for it in items)
        if dict(dc) != WANT_DAYS[name]:
            problems.append(f'{name}: day coverage {dict(sorted(dc.items()))}, want {WANT_DAYS[name]}')
        if name == 'exam' and any(it['day'] == 3 for it in items):
            problems.append('exam contains a Day 3 item')
        for i, it in enumerate(items, 1):
            bad = length_issues(it)
            if bad:
                problems.append(f'{name} Q{i}: option lengths outside ±20%: ' + ' | '.join(f'{len(o)}:{o}' for o in it['o']))
        lc = sum(longest_correct(it) for it in items)
        exempt = sum(1 for it in items if sum(len(o) for o in it['o']) / 4 < 8)
        report.append((name, dict(sorted(kc.items())), dict(sorted(dc.items())), lc, len(items), exempt))
        if lc > 0.3 * len(items):
            problems.append(f'{name}: correct option is the longest in {lc}/{len(items)} items (> 30%)')
        built[name] = arrange(items, key)

    write_md(built, report)
    write_js(built)
    for name, kc, dc, lc, n, ex in report:
        print(f'{TITLES[name]:<12} items {n} · keys {kc} · days {dc} · correct-is-longest {lc}/{n} = {lc / n:.0%} · short-option items {ex}')
    if problems:
        print('PROBLEMS:')
        for p in problems:
            print('  -', p)
        return 1
    print('ALL ASSESSMENT CHECKS PASS')
    return 0


def write_js(built):
    qs = {n: [{'q': it['q'], 'options': it['options'], 'topic': it['concept'], 'day': it['day']} for it in items]
          for n, items in built.items()}
    with open(os.path.join(ROOT, 'assessment', 'questions.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by tools/build_assessments.py from tools/assess/items.py. No answers in this file. */\n')
        fh.write('var TESTS = ' + json.dumps(qs, ensure_ascii=False, indent=1) + ';\n')
    keys = {}
    for n, items in built.items():
        keys[n] = {'key': ''.join(it['letter'] for it in items)}
        if n != 'exam':
            keys[n]['why'] = [it['why'] for it in items]
    blob = base64.b64encode(json.dumps(keys, ensure_ascii=False).encode('utf-8')).decode('ascii')
    with open(os.path.join(ROOT, 'assessment', 'keys.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Answer keys and explanations, base64-encoded so they are not readable at a glance.\n'
                 '   Generated by tools/build_assessments.py. The exam has no explanations on the site. */\n')
        fh.write(f'var TEST_KEYS_B64 = "{blob}";\n')


def write_md(built, report):
    out = ['# Assessments — pre-test, post-test, theory exam', '',
           'Generated by `tools/build_assessments.py` from `tools/assess/items.py`. Each item has 4 options and a one-line',
           'explanation. Keys were fixed in advance (irregular order) and the correct option is placed at that letter.', '',
           '| Instrument | When | Items | Covers |', '|---|---|---|---|',
           '| Pre-test | Day 1 B1 | 20 | All 3 days (7 / 7 / 6) — baseline |',
           '| Theory exam | Day 3 B1 | 30, closed book, 40 min | **Days 1–2 only** (15 / 15) — it runs before any Day 3 teaching |',
           '| Post-test | Day 3 close | 20 | Same 20 concepts as the pre-test, different questions (7 / 7 / 6) |', '']
    for n, items in built.items():
        out += [f'## {TITLES[n]}', '', f'Key: `{"".join(it["letter"] for it in items)}`', '']
        for i, it in enumerate(items, 1):
            out.append(f'**{i}. [Day {it["day"]} · {it["concept"]}]** {it["q"]}')
            out.append('')
            for k, o in enumerate(it['options']):
                mark = ' ✔' if k == it['answer'] else ''
                out.append(f'- {L[k]}. {o}{mark}')
            out.append(f'- *Answer {it["letter"]} — {it["why"]}*')
            out.append('')
    out += ['## Pre-test ↔ post-test concept map', '', '| # | Concept | Pre-test | Post-test |', '|---|---|---|---|']
    for i, (a, b) in enumerate(zip(built['pretest'], built['posttest']), 1):
        out.append(f'| {i} | {a["concept"]} | {a["q"][:60]}… | {b["q"][:60]}… |')
    out += ['', '## Distribution table', '', '| Instrument | Items | A | B | C | D | Day 1 | Day 2 | Day 3 |', '|---|---|---|---|---|---|---|---|---|']
    for n, kc, dc, lc, total, ex in report:
        out.append(f'| {TITLES[n]} | {total} | {kc.get("A", 0)} | {kc.get("B", 0)} | {kc.get("C", 0)} | {kc.get("D", 0)} | {dc.get(1, 0)} | {dc.get(2, 0)} | {dc.get(3, 0)} |')
    out += ['', '## Longest-option check', '',
            'Counts how often the correct option is strictly the longest of the four. Rule: at most 30 % of items.', '',
            '| Instrument | Correct is longest | Share | Pass |', '|---|---|---|---|']
    for n, kc, dc, lc, total, ex in report:
        out.append(f'| {TITLES[n]} | {lc} / {total} | {lc / total:.0%} | {"✅" if lc <= 0.3 * total else "❌"} |')
    out += ['', 'Option-length rule: every option is within ±20 % of the mean length of its item; items whose options',
            'average under 8 characters (numbers, short formulas such as `(480, 640, 3)` or `0.60`) are exempt.', '']
    with open(os.path.join(ROOT, 'content', 'assessments.md'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out))


if __name__ == '__main__':
    sys.exit(main())
